    CATALOG[filiere]?[niveau]?[semestre] ?? [];

List<String> allMatieres({String? filiere, String? niveau}) {
  if (filiere == null) {
    final set = <String>{};
    for (final n in CATALOG.values) {
      for (final s in n.values) {
        for (final l in s.values) {
          set.addAll(l);
        }
      }
    }
    final list = set.toList()..sort();
    return list;
  }
  final set = <String>{};
  final nv = niveau == null
      ? CATALOG[filiere]!.values
      : [CATALOG[filiere]![niveau]!];
  for (final s in nv) {
    for (final l in s.values) {
      set.addAll(l);
    }
  }
  final list = set.toList()..sort();
  return list;
}